import { describe, expect, it } from "vitest";
import { toAreas, type AreaSource } from "./toAreas";

/** 좌표는 위도만 바꿔서 중앙값을 쉽게 셈한다 */
const lib = (region: string, address: string | null, lat: number | null = 37): AreaSource => ({
  region,
  address,
  location: lat === null ? null : { lat, lng: 127 },
});

const names = (sources: AreaSource[]) => toAreas(sources).map((a) => `${a.sido} ${a.name}`);

describe("toAreas", () => {
  it("시도와 시군구로 묶고, 대표 지점은 그 동네 도서관 좌표의 중앙값이다 (짝수 개면 가운데 두 값의 평균)", () => {
    expect(
      toAreas([
        lib("11", "서울특별시 노원구 동일로 1405", 37.6),
        lib("11", "서울특별시 노원구 노원로 28", 37.7),
      ]),
    ).toEqual([{ sido: "서울특별시", name: "노원구", center: { lat: 37.65, lng: 127 } }]);
  });

  it("대표 지점은 소수점 6자리로 반올림한다", () => {
    const [area] = toAreas([
      lib("11", "서울특별시 노원구 가", 37.1234561),
      lib("11", "서울특별시 노원구 나", 37.1234564),
    ]);
    expect(area.center.lat).toBe(37.123456);
  });

  it("좌표가 멀리 틀린 도서관 하나에 대표 지점이 끌려가지 않는다 (광주 북구 하서로 299가 서울 좌표)", () => {
    const [area] = toAreas([
      lib("24", "광주광역시 북구 가", 35.17),
      lib("24", "광주광역시 북구 나", 35.18),
      lib("24", "광주광역시 북구 다", 35.19),
      { region: "24", address: "전남광주통합특별시 북구 하서로 299", location: { lat: 37.6, lng: 127.02 } },
    ]);
    expect(area.center).toEqual({ lat: 35.185, lng: 127 });
  });

  it("시 아래 구가 있으면 '수원시 장안구'처럼 구 단위로 나눈다", () => {
    expect(
      names([
        lib("31", "경기도 수원시 장안구 송정로 1"),
        lib("31", "경기도 수원시 장안구 수성로 2"),
        lib("31", "경기도 수원시 권선구 권선로 3"),
        lib("37", "경상북도 포항시 북구 양학로 4"),
      ]),
    ).toEqual(["경기도 수원시 권선구", "경기도 수원시 장안구", "경상북도 포항시 북구"]);
  });

  it("시군구가 없는 주소(세종)는 시도 하나를 동네로 본다", () => {
    expect(toAreas([lib("29", "세종특별자치시 한누리대로 2023,")])).toEqual([
      { sido: "세종특별자치시", name: "세종특별자치시", center: { lat: 37, lng: 127 } },
    ]);
  });

  it("첫 단어가 정식 시도 이름이 아니면(통합특별시) 지역 코드의 시도를 쓴다", () => {
    expect(
      toAreas([
        lib("24", "광주광역시 북구 서암대로 1", 35.1),
        lib("24", "전남광주통합특별시 북구 하서로 299", 35.2),
        lib("36", "전남광주통합특별시 광양시 안산길 23", 34.9),
      ]),
    ).toEqual([
      { sido: "광주광역시", name: "북구", center: { lat: 35.15, lng: 127 } },
      { sido: "전라남도", name: "광양시", center: { lat: 34.9, lng: 127 } },
    ]);
  });

  it("주소의 시도가 지역 코드와 달라도 정식 시도 이름이면 주소를 따른다", () => {
    expect(names([lib("33", "강원특별자치도 원주시 향교길 77")])).toEqual(["강원특별자치도 원주시"]);
  });

  it("시 안에서 구가 있는 주소가 절반 이하면 구를 무시하고 시 하나로 묶는다", () => {
    const areas = toAreas([
      lib("31", "경기도 부천시 경인옛로38번길 41", 37.1),
      lib("31", "경기도 부천시 성오로149번길 18, 3층", 37.2),
      lib("31", "경기도 부천시 원미구 소향로 1", 37.3),
      lib("31", "경기도 부천시 원미구 소향로 2", 37.4),
    ]);
    expect(areas).toEqual([{ sido: "경기도", name: "부천시", center: { lat: 37.25, lng: 127 } }]);
  });

  it("구 단위로 나눈 시에서 구가 없는 주소는 대표 지점 계산에서만 뺀다", () => {
    const areas = toAreas([
      lib("31", "경기도 수원시 장안구 송정로 1", 37.2),
      lib("31", "경기도 수원시 장안구 수성로 2", 37.4),
      lib("31", "경기도 수원시 권선구 권선로 3", 37.1),
      lib("31", "경기도 수원시 매송고색로 620", 38.0),
    ]);
    expect(areas).toEqual([
      { sido: "경기도", name: "수원시 권선구", center: { lat: 37.1, lng: 127 } },
      { sido: "경기도", name: "수원시 장안구", center: { lat: 37.3, lng: 127 } },
    ]);
  });

  it.each([
    ["주소 없음", null, 37],
    ["주소가 '-'", "-", 37],
    ["주소가 빈 문자열", "  ", 37],
    ["좌표 없음", "서울특별시 강남구 테헤란로 1", null],
  ])("%s인 도서관은 빼고, 남은 도서관이 없는 동네는 목록에 없다", (_, address, lat) => {
    expect(names([lib("11", "서울특별시 노원구 동일로 1405"), lib("11", address, lat)])).toEqual(["서울특별시 노원구"]);
  });

  it("시도는 정보나루 지역 코드 순, 시도 안에서는 가나다순이다", () => {
    expect(
      names([
        lib("31", "경기도 고양시 덕양구 가"),
        lib("21", "부산광역시 해운대구 가"),
        lib("11", "서울특별시 노원구 가"),
        lib("11", "서울특별시 강남구 가"),
        lib("31", "경기도 가평군 가"),
      ]),
    ).toEqual(["서울특별시 강남구", "서울특별시 노원구", "부산광역시 해운대구", "경기도 가평군", "경기도 고양시 덕양구"]);
  });
});
